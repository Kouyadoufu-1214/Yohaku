/**
 * 日常生活支援。各項目に「無理のない小さな行動」を一つずつ提示する。
 * 行動は強制しない（「今はしない」「別の方法を見る」を必ず用意する）。
 * 医学的な判断・治療方法の指示は行わない。
 * ※ 心理・医療の専門家による内容確認前（docs/content-review.md 参照）
 */

export interface LifeSuggestion {
  text: string;
  hint?: string;
}

export interface LifeItem {
  id: string;
  label: string;
  /** 最初に添えることば（評価や励ましではなく、受け止め） */
  note: string;
  suggestions: LifeSuggestion[];
  /** 関連する画面への案内 */
  links?: { label: string; to: string }[];
  /** 医療機関・相談先への案内を表示する */
  careNote?: string;
}

export interface LifeCategory {
  id: string;
  label: string;
  description: string;
  items: LifeItem[];
}

